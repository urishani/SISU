def parse(blob: str) -> dict[str, str]:
    words: dict[str, str] = {}
    for line in blob.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise SystemExit(f"Bad lexicon line: {line!r}")
        he, en = line.split("\t", 1)
        he, en = he.strip(), en.strip()
        if not he or not en:
            raise SystemExit(f"Empty lexicon pair: {line!r}")
        if "//" in en or "replace" in en:
            raise SystemExit(f"Placeholder left in: {line!r}")
        words[he] = en
    return words


def main() -> None:
    words = parse(STEMS)
    words.update(parse(RAW))
    out = Path(__file__).resolve().parents[1] / "hebrew_phonetic_lexicon.json"
    payload = {
        "version": 1,
        "style": "israeli-english-catalog",
        "note": "Phonetic English spelling, not translation. Title Case. Built from SISU scan titles.",
        "words": dict(sorted(words.items(), key=lambda item: (-len(item[0]), item[0]))),
    }
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(words)} words to {out}")


if __name__ == "__main__":
    main()
